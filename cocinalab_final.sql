CREATE DATABASE IF NOT EXISTS `login` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `login`;

SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO";
SET time_zone = "+00:00";

DROP TABLE IF EXISTS `receta_ingrediente`;
DROP TABLE IF EXISTS `recetas`;
DROP TABLE IF EXISTS `ingredientes`;
DROP TABLE IF EXISTS `registros`;
DROP TABLE IF EXISTS `pago`;

-- ---------------- registros ----------------
CREATE TABLE `registros` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `Usuario` VARCHAR(200) NOT NULL,
  `Correo` VARCHAR(200) NOT NULL,
  `Contrasena` VARCHAR(255) NOT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------- ingredientes ----------------
CREATE TABLE `ingredientes` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `Nombre` VARCHAR(200) NOT NULL,
  `Tipo` VARCHAR(200) DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------- recetas (reparada: antes PK era ingredientes) ----------------
CREATE TABLE `recetas` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `Imagenes` VARCHAR(255) DEFAULT NULL,
  `Nombre` VARCHAR(200) NOT NULL,
  `Procedimiento` TEXT,
  `TipoC` VARCHAR(50) DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------- receta_ingrediente ----------------
CREATE TABLE `receta_ingrediente` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `receta_id` INT NOT NULL,
  `ingrediente_id` INT NOT NULL,
  `cantidad` VARCHAR(100) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `receta_id` (`receta_id`),
  KEY `ingrediente_id` (`ingrediente_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------- pago (reparada: Fecha timestamp(200) era sintaxis invalida) ----------------
CREATE TABLE `pago` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `Metodo` VARCHAR(200) DEFAULT NULL,
  `Fecha` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  `Tarjeta` VARCHAR(200) DEFAULT NULL,
  `Vencimiento` VARCHAR(200) DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

